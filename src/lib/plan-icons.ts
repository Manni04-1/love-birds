/** Lower case, accents and apostrophes gone, everything but letters and numbers turned to spaces. */
function normalise(text: string): string {
  return ` ${text
    .toLowerCase()
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .replace(/['’]/g, '')
    .replace(/[^a-z0-9]+/g, ' ')
    .trim()} `;
}

type Matcher = (padded: string, words: string[]) => boolean;

function matcher(term: string): Matcher {
  if (term.includes(' ')) return (padded) => padded.includes(` ${term} `);
  if (term.endsWith('*')) {
    const stem = term.slice(0, -1);
    return (_, words) => words.some((w) => w.startsWith(stem));
  }
  return (_, words) => words.includes(term);
}

const COMPILED: [string, Matcher[]][] = GUESSES.map(([emoji, spec]) => [emoji, spec.split(',').map((term) => matcher(term.trim()))]);

/** The emoji a plan's name suggests, such as 🍽️ for "Dinner at Talisman". Null when nothing fits. */
export function guessEmoji(title: string): string | null {
  const start = title.trim();
  // An emoji typed at the start of the name wins.
  const typed = ALL_EMOJI.find((em) => start.startsWith(em) || start.startsWith(em.replace(/️/g, '')));
  if (typed) return typed;
  const padded = normalise(title);
  const words = padded.trim().split(' ');
  for (const [emoji, tests] of COMPILED) if (tests.some((t) => t(padded, words))) return emoji;
  return null;
}

/** The icon a plan gets when nobody picked one: a guess from its name, a suitcase for a trip, or a calendar. */
export function autoIcon(title: string, severalDays = false): PlanIcon {
  return { emoji: guessEmoji(title) ?? (severalDays ? '🧳' : '📅'), glyph: null };
}

const GLYPH_NAMES = new Set<string>(GLYPH_GROUPS.flatMap((grp) => grp.items.map((i) => i.glyph)));

/** The icon to show for a plan: the one picked for it, or a guess from its name. */
export function iconFor(plan: Pick<Plan, 'title' | 'day' | 'end_day' | 'emoji' | 'glyph'>): PlanIcon {
  const glyph = plan.glyph && GLYPH_NAMES.has(plan.glyph) ? (plan.glyph as AndroidSymbol) : null;
  if (plan.emoji) return { emoji: plan.emoji, glyph };
  return autoIcon(plan.title, !!plan.end_day && plan.end_day > plan.day);
}

/** True when a plan's icon is the one its name suggests, so it can follow the name when that changes. */
export function followsName(plan: Pick<Plan, 'title' | 'day' | 'end_day' | 'emoji' | 'glyph'>): boolean {
  if (!plan.emoji) return true;
  const auto = autoIcon(plan.title, !!plan.end_day && plan.end_day > plan.day);
  return !plan.glyph && plan.emoji === auto.emoji;
}

export const sameIcon = (a: PlanIcon, b: PlanIcon) => a.emoji === b.emoji && a.glyph === b.glyph;

/** Emoji and drawn icons whose words start with what you typed, for the search box. */
export function searchIcons(query: string): { emoji: EmojiChoice[]; glyphs: GlyphChoice[] } {
  const q = normalise(query).trim();
  if (!q) return { emoji: [], glyphs: [] };
  const terms = q.split(' ');
  const hit = (words: string, label: string) => {
    const all = `${words} ${label}`.toLowerCase().split(' ');
    return terms.every((t) => all.some((w) => w.startsWith(t)));
  };
  return {
    emoji: EMOJI_GROUPS.flatMap((grp) => grp.items.filter((i) => hit(i.words, grp.label))),
    glyphs: GLYPH_GROUPS.flatMap((grp) => grp.items.filter((i) => hit(i.words, grp.label))),
  };
}

/** The group an icon is in, to open the picker there. */
export function groupOf(icon: PlanIcon): string {
  if (icon.glyph) return GLYPH_GROUPS.find((grp) => grp.items.some((i) => i.glyph === icon.glyph))?.key ?? GLYPH_GROUPS[0].key;
  return EMOJI_GROUPS.find((grp) => grp.items.some((i) => i.emoji === icon.emoji))?.key ?? EMOJI_GROUPS[0].key;
}
